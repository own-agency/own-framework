/**
 * Wraps core/video's own <video> in a Video.js player (src/js/scripts/
 * video.js registers the elements) — server-side, so the layout is final on
 * first paint instead of re-flowing once the script runs.
 *
 * Only videos WITH "controls": an editor who turns off "Toon afspeelknoppen"
 * wants a bare autoplay/loop video, no player UI on top. blocks/hero's own
 * background video is its own block, never core/video, so it's never touched.
 * Front end only — render_block never runs for the editor's client-side
 * core/video preview, which keeps native controls there.
 *
 * The neutral skin's layout is rendered here in the light DOM
 * (video-player/skin.html, generated by src/js/scripts/video-skin.mjs) instead of via
 * <video-neutral-skin>: that element puts its controls in a shadow root,
 * which can't be changed from outside. In the light DOM the theme adds a big
 * centred play button and keeps the control bar hidden until the first play
 * (src/css/components/video.css). After a @videojs/html update, run
 * `pnpm video-skin` to regenerate skin.html.
 *
 * Moved on the way in, per the Video.js docs:
 * - "controls" is dropped: the skin draws its own, and Video.js doesn't hide
 *   native controls by itself (known gap, videojs/v10#1160).
 * - "poster" moves to <video-player> and the skin's poster <img>: a poster
 *   on the <video> only sets the browser's own poster.
 * - The aspect ratio comes from the attachment's own width/height, so a
 *   vertical or square upload isn't forced into 16:9. External URLs (no
 *   attachment ID) fall back to the video's intrinsic size via CSS.
 */
add_filter(
    "render_block_core/video",
    function (string $content, array $block): string {
        static $instance = 0;

        $processor = new WP_HTML_Tag_Processor($content);
        if (!$processor->next_tag("video") || $processor->get_attribute("controls") === null) {
            return $content;
        }

        $template = ownframework_video_skin_template();
        if ($template === "") {
            return $content;
        }

        $poster = (string) $processor->get_attribute("poster");
        $processor->remove_attribute("controls");
        $processor->remove_attribute("poster");
        $content = $processor->get_updated_html();

        $container_style = "";
        $meta = !empty($block["attrs"]["id"]) ? wp_get_attachment_metadata((int) $block["attrs"]["id"]) : [];
        if (!empty($meta["width"]) && !empty($meta["height"])) {
            $container_style = sprintf(' style="aspect-ratio:%d / %d;box-sizing:border-box"', $meta["width"], $meta["height"]);
        }

        // Without a src the poster element fills in the player's poster
        // itself; an empty src="" would make the browser request the page.
        $template = $poster !== ""
            ? str_replace("{poster}", esc_url($poster), $template)
            : str_replace(' src="{poster}"', "", $template);
        $template = str_replace("{uid}", "own-vjs-" . ++$instance, $template);
        // "not-prose": the layout now sits in the page's DOM, so .prose's
        // img/button/list rules would otherwise reach into the player.
        $template = preg_replace(
            '/^<media-container class="([^"]*)"/',
            '<media-container class="$1 own-video-player not-prose"' . $container_style,
            $template,
            1,
        );

        // <media-i18n> without "lang" follows <html lang> (nl-NL → the shipped
        // "nl" pack).
        $open = sprintf(
            '<media-i18n><video-player%s>',
            $poster !== "" ? ' poster="' . esc_url($poster) . '"' : "",
        );
        $close = "</video-player></media-i18n>";

        return preg_replace_callback(
            '#<video\b.*?</video>#s',
            fn(array $m): string => $open . str_replace("{video}", $m[0], $template) . $close,
            $content,
            1,
        ) ?? $content;
    },
    10,
    2,
);

/**
 * The generated skin layout, without its header comment. Read once per
 * request.
 */
function ownframework_video_skin_template(): string
{
    static $template = null;
    if ($template === null) {
        $raw = (string) @file_get_contents(__DIR__ . "/video-player/skin.html");
        $template = trim(preg_replace("/^<!--.*?-->/s", "", $raw) ?? "");
    }
    return $template;
}
